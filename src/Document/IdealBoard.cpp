#include "IdealBoard.h"

#include <QMap>
#include <QRegularExpression>
#include "Document/Components/ComponentBlueprint.h"
#include "Document/Components/ComponentInstance.h"



QString BoardPins::identifier(const QString& name) {
    QString id = name.toUpper();
    id.replace(QRegularExpression("[^A-Z0-9]+"), "_");
    id.remove(QRegularExpression("^_+|_+$"));
    if (id.isEmpty() || id[0].isDigit()) return QString();
    return id;
}

static void collectInto(ComponentInstance* comp, QList<ComponentInstance*>& out) {
    if (!comp) return;
    out.append(comp);
    for (ComponentInstance* child : comp->children) collectInto(child, out);
}

QList<ComponentInstance*> BoardPins::collect(ComponentInstance* root) {
    QList<ComponentInstance*> out;
    collectInto(root, out);
    return out;
}

QList<int> BoardPins::aliasedUids(const QList<ComponentInstance*>& parts) {
    QMap<QString, QList<int>> byName;
    for (ComponentInstance* comp : parts) {
        ComponentBlueprint* bp = comp->getBlueprint();
        if (!bp) continue;
        for (const PinDef& pin : bp->pins) {
            if (pin.isBoardPin()) { byName[identifier(comp->name)].append(comp->uid); break; }
        }
    }
    QList<int> out;
    for (auto it = byName.begin(); it != byName.end(); ++it)
        if (!it.key().isEmpty() && it.value().size() == 1) out.append(it.value().first());
    return out;
}

BoardPin BoardPins::make(ComponentInstance* comp, const PinDef& pin, bool aliased) {
    BoardPin bpin;
    const QString pinName = identifier(pin.id);
    bpin.uid = comp->uid;
    bpin.pinId = pin.id;
    bpin.type = pin.type;
    bpin.constant = QString("COMP_%1_%2").arg(comp->uid).arg(pinName);
    if (aliased) bpin.alias = identifier(comp->name) + "_" + pinName;
    bpin.partName = comp->name;
    bpin.modelId = comp->modelId;
    return bpin;
}

QString BoardPins::header(const QList<BoardPin>& pins, const QString& intro) {
    QString h = intro;
    h += "#pragma once\n";
    int lastUid = -1;
    for (const BoardPin& p : pins) {
        if (p.uid != lastUid) {
            h += QString("\n// %1 (%2, uid %3)\n").arg(p.partName, p.modelId).arg(p.uid);
            lastUid = p.uid;
        }
        h += QString("constexpr int %1 = %2;   // %3\n").arg(p.constant).arg(p.number).arg(p.type);
        if (!p.alias.isEmpty()) h += QString("constexpr int %1 = %2;\n").arg(p.alias, p.constant);
    }
    return h;
}



IdealBoard IdealBoard::fromTree(ComponentInstance* root) {
    const QList<ComponentInstance*> parts = BoardPins::collect(root);
    const QList<int> aliased = BoardPins::aliasedUids(parts);

    IdealBoard board;
    for (ComponentInstance* comp : parts) {
        ComponentBlueprint* bp = comp->getBlueprint();
        if (!bp || comp->uid < 0) continue;
        for (int i = 0; i < bp->pins.size() && i < kPinsPerPart; ++i) {
            const PinDef& pin = bp->pins[i];
            if (!pin.isBoardPin() || BoardPins::identifier(pin.id).isEmpty()) continue;
            BoardPin bpin = BoardPins::make(comp, pin, aliased.contains(comp->uid));
            bpin.number = comp->uid * kPinsPerPart + i;
            board.boardPins.append(bpin);
        }
    }
    return board;
}



QList<BoardPin> IdealBoard::pinsOf(int uid) const {
    QList<BoardPin> out;
    for (const BoardPin& p : boardPins) if (p.uid == uid) out.append(p);
    return out;
}



const BoardPin* IdealBoard::find(int number) const {
    for (const BoardPin& p : boardPins) if (p.number == number) return &p;
    return nullptr;
}



QString IdealBoard::header(const QString& projectName) const {
    QString intro;
    intro += QString("// robot_pins.h: generated by RoboticsStudio for \"%1\" (Prototype level, ideal board).\n").arg(projectName);
    intro += "// Regenerated on every Play; do not edit. A pin number is the part's uid * 100 + the\n";
    intro += "// pin's index in its part file, so it stays the same while the part exists.\n";
    return BoardPins::header(boardPins, intro);
}
