#include "RealBoard.h"

#include <QHash>
#include <algorithm>
#include "Document/Netlist.h"
#include "Document/Components/ComponentBlueprint.h"
#include "Document/Components/ComponentInstance.h"



RealBoard RealBoard::build(ComponentInstance* board, ComponentInstance* root, const Netlist& netlist) {
    RealBoard rb;
    ComponentBlueprint* boardBp = board ? board->getBlueprint() : nullptr;
    if (!boardBp || !boardBp->board.present) return rb;
    rb.boardComp = board;

    const QList<ComponentInstance*> parts = BoardPins::collect(root);
    const QList<int> aliased = BoardPins::aliasedUids(parts);
    QHash<int, ComponentInstance*> byUid;
    for (ComponentInstance* c : parts) byUid.insert(c->uid, c);

    const QList<Net> nets = netlist.nets();
    const QHash<PinRef, int> netOf = Netlist::indexOf(nets);
    QSet<PinRef> listed;

    for (const PinDef& bpin : boardBp->pins) {
        if (bpin.number < 0) continue;
        if (bpin.internal) {
            if (!bpin.isBoardPin() || BoardPins::identifier(bpin.id).isEmpty()) continue;
            BoardPin p = BoardPins::make(board, bpin, aliased.contains(board->uid));
            p.number = bpin.number;
            p.boardPinId = bpin.id;
            rb.boardPins.append(p);
            continue;
        }
        const int net = netOf.value(PinRef{board->uid, bpin.id}, -1);
        if (net < 0) continue;
        for (const PinRef& r : nets[net].pins) {
            if (r.uid == board->uid || listed.contains(r)) continue;
            ComponentInstance* comp = byUid.value(r.uid, nullptr);
            ComponentBlueprint* bp = comp ? comp->getBlueprint() : nullptr;
            if (!bp) continue;
            for (const PinDef& pin : bp->pins) {
                if (pin.id != r.pin) continue;
                if (pin.isBoardPin() && !BoardPins::identifier(pin.id).isEmpty()) {
                    BoardPin p = BoardPins::make(comp, pin, aliased.contains(comp->uid));
                    p.number = bpin.number;
                    p.boardPinId = bpin.id;
                    rb.boardPins.append(p);
                    listed.insert(r);
                }
                break;
            }
        }
    }

    // Grouped by part, pins in their .rsdef order (as on the ideal board).
    auto pinIndex = [&](const BoardPin& p) {
        ComponentInstance* comp = byUid.value(p.uid, nullptr);
        if (!comp || !comp->getBlueprint()) return 0;
        const auto& pins = comp->getBlueprint()->pins;
        for (int i = 0; i < pins.size(); ++i) if (pins[i].id == p.pinId) return i;
        return 0;
    };
    std::stable_sort(rb.boardPins.begin(), rb.boardPins.end(), [&](const BoardPin& a, const BoardPin& b) {
        if (a.uid != b.uid) return a.uid < b.uid;
        return pinIndex(a) < pinIndex(b);
    });
    return rb;
}



const BoardDef& RealBoard::def() const {
    static const BoardDef none;
    ComponentBlueprint* bp = boardComp ? boardComp->getBlueprint() : nullptr;
    return bp ? bp->board : none;
}



QList<BoardPin> RealBoard::pinsOf(int uid) const {
    QList<BoardPin> out;
    for (const BoardPin& p : boardPins) if (p.uid == uid) out.append(p);
    return out;
}



const BoardPin* RealBoard::find(int number) const {
    for (const BoardPin& p : boardPins) if (p.number == number) return &p;
    return nullptr;
}



QString RealBoard::variantHeader() const {
    const BoardDef& d = def();
    const QString model = boardComp && boardComp->getBlueprint() ? boardComp->getBlueprint()->meta.name : QString();
    QString h = QString("// pins_arduino.h: %1's pin names, as the real Arduino core's variant for\n"
                        "// %2 defines them (from the board's .rsdef, board.variant). Generated by RoboticsStudio.\n"
                        "#pragma once\n#include <stdint.h>\n\n").arg(model, d.fqbn);
    for (auto it = d.variantPins.begin(); it != d.variantPins.end(); ++it) {
        if (it.key() == "LED_BUILTIN") h += QString("#define LED_BUILTIN %1\n").arg(it.value());
        else h += QString("static const uint8_t %1 = %2;\n").arg(it.key()).arg(it.value());
    }
    return h;
}



QStringList RealBoard::defines() const {
    return def().defines;
}
